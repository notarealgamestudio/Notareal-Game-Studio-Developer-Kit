#!/usr/bin/env python3
"""Pulls reusable data out of the Korg DS-10 and KORG M01 ROMs (NitroFS) for the Memphis Sigil music engine and the dev kit's music tools.
Usage: korg_extract.py <DS-10.nds> <M01.nds>     Writes library/korg_ds10_m01.json, kit/nrsigil_data.js, engine/sigil/source/groove_bank.h
What is decoded: DS-10 synth patches (24 x 8-char name + 31 parameter bytes), DS-10 demo songs (tempo + pattern chain), M01 sound-program names (340),
M01 drum-pattern bank (576 step blocks = 36 patterns x 16 steps x 24 lanes). Lane / parameter MEANING is only partly decoded: see docs/KORG_DATA.md."""
import struct, json, sys, os
K = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
def nitro(path):
    d = open(path, 'rb').read(); fnt_o, fnt_s, fat_o, fat_s = struct.unpack('<4I', d[0x40:0x50])
    ents = [struct.unpack('<2I', d[fat_o + i * 8:fat_o + i * 8 + 8]) for i in range(fat_s // 8)]; names = {}
    def walk(dirid, prefix):
        o = fnt_o + (dirid & 0xfff) * 8; base = fnt_o + struct.unpack('<I', d[o:o + 4])[0]; fid = struct.unpack('<H', d[o + 4:o + 6])[0]; p = base
        while True:
            t = d[p]; p += 1
            if t == 0: break
            ln = t & 0x7f; nm = d[p:p + ln].decode('latin1'); p += ln
            if t & 0x80: sub = struct.unpack('<H', d[p:p + 2])[0]; p += 2; walk(sub, prefix + nm + '/')
            else: names[prefix + nm] = ents[fid]; fid += 1
    walk(0xf000, ''); return d, names
def get(d, n, k): a, b = n[k]; return d[a:b]
def main(ds10, m01):
    d, n = nitro(ds10); out = {'source': 'Korg DS-10 + KORG M01 ROM scan (structure and parameter values only; no audio or art copied)'}
    out['ds10_patches'] = []
    for i in range(24):
        b = get(d, n, f'data/demo/ds10synth{i:02d}.dat'); out['ds10_patches'].append({'name': b[16:32].split(b'\0')[0].decode('latin1'), 'params': list(b[32:63])})
    out['ds10_demos'] = []
    for k in sorted(x for x in n if x.startswith('data/demo/ds10demo') or x.endswith('ds10init.dat')):
        b = get(d, n, k); ch = []; p = 0x3c
        while p + 2 <= len(b) and struct.unpack('<H', b[p:p + 2])[0] != 0xffff and len(ch) < 64: ch.append(struct.unpack('<H', b[p:p + 2])[0]); p += 2
        out['ds10_demos'].append({'file': k.split('/')[-1], 'name': ''.join(c for c in b[0x24:0x2c].split(b'\0')[0].decode('latin1') if ' ' <= c <= '~'), 'bpm': struct.unpack('<I', b[0x14:0x18])[0], 'chain': ch})
    m, mn = nitro(m01); ms = get(m, mn, 'mspara.bin.mod'); progs = []
    for i in range(0, len(ms) - 11, 12):
        nm = ms[i:i + 8].decode('latin1').strip()
        if not nm: continue
        progs.append({'name': nm, 'a': struct.unpack('<H', ms[i + 8:i + 10])[0], 'b': struct.unpack('<H', ms[i + 10:i + 12])[0]})
    out['m01_programs'] = progs; out['m01_kits'] = [p['name'] for p in progs if p['a'] == 12]
    dp = get(m, mn, 'drumpattern.bin'); grooves = []
    for p in range(len(dp) // 48 // 16):
        g = [[0] * 16 for _ in range(8)]
        for s in range(16):
            blk = dp[(p * 16 + s) * 48:(p * 16 + s + 1) * 48]
            for v in range(24):
                x = blk[v * 2]
                if x: g[v % 8][s] = max(g[v % 8][s], 40 + min(x, 15) * 5)
        if sum(1 for r in g for x in r if x) >= 4: grooves.append(g)
    out['grooves'] = grooves
    json.dump(out, open(f'{K}/library/korg_ds10_m01.json', 'w'))
    open(f'{K}/kit/nrsigil_data.js', 'w').write('/* generated by tools/korg_extract.py from the Korg DS-10 / KORG M01 ROMs: do not edit */\n(function (root) { const D = ' + json.dumps(out, separators=(',', ':')) + '; if (typeof module !== "undefined") module.exports = D; else root.NRSigilData = D; })(typeof window !== "undefined" ? window : globalThis);\n')
    h = '// Groove bank mined from the KORG M01 ROM (drumpattern.bin: 576 step blocks x 24 lanes). Lanes folded onto the 8 Sigil rows (lane mod 8).\n// tools/korg_extract.py regenerates this; the lane meaning is only partly decoded, see docs/KORG_DATA.md.\n#pragma once\n#define GRV_N %d\nstatic const unsigned char GRV[GRV_N][8][16] = {\n' % len(grooves)
    h += ''.join('{' + ','.join('{' + ','.join(map(str, r)) + '}' for r in g) + '},\n' for g in grooves) + '};\n'
    open(f'{K}/engine/sigil/source/groove_bank.h', 'w').write(h)
    print('patches', len(out['ds10_patches']), 'demos', [(x['name'], x['bpm'], len(x['chain'])) for x in out['ds10_demos']], 'programs', len(progs), 'kits', len(out['m01_kits']), 'grooves', len(grooves))
if __name__ == '__main__': main(sys.argv[1], sys.argv[2])
